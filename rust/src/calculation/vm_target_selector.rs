struct EvaluatedCandidate<'a> {
    candidate: &'a VmSizeCandidate,
    disks: Vec<SelectedManagedDisk>,
    hourly_rate: Option<DecimalValue>,
}

/// Selects one Azure VM size and one managed disk per persistent source volume.
///
/// Ranking follows section 8.4: lifecycle, then reviewed generation rank, then vCPU surplus, then
/// memory surplus, aggregate disk-capability surplus, complete pay-as-you-go VM price, and finally
/// the ARM SKU name.
pub fn select_vm_target(
    vm_catalog: &VmCapabilityCatalog,
    disk_catalog: &ManagedDiskCatalog,
    request: &VmTargetSelectionRequest<'_>,
) -> Result<VmTargetSelection, VmTargetSelectionError> {
    validate_request(request)?;

    let requested_lineage = request.source_class.target_lineage();
    let mut evaluations = Vec::new();
    let mut eligible = Vec::new();

    for candidate in &vm_catalog.candidates {
        let mut rejection_reasons = Vec::new();
        let mut disks = Vec::new();

        if !candidate
            .azure_region
            .eq_ignore_ascii_case(request.azure_region)
        {
            // A candidate from another region is not a rejection worth reporting to the user.
            continue;
        }
        if candidate.lineage != requested_lineage {
            if request
                .requested_target_arm_sku
                .is_some_and(|requested| candidate.arm_sku_name.eq_ignore_ascii_case(requested))
            {
                evaluations.push(VmCandidateEvaluation {
                    arm_sku_name: candidate.arm_sku_name.clone(),
                    vcpus: candidate.vcpus,
                    memory_gb: candidate.memory_gb,
                    eligible: false,
                    rejection_reasons: vec![reason(
                        VmSelectionReasonCode::LineageMismatch,
                        format!(
                            "{} is not in the required {requested_lineage:?} lineage.",
                            candidate.arm_sku_name
                        ),
                    )],
                });
            }
            continue;
        }
        if candidate.lifecycle != VmLifecycle::Current {
            rejection_reasons.push(reason(
                VmSelectionReasonCode::LifecycleIneligible,
                format!("{} is not a current generation.", candidate.arm_sku_name),
            ));
        }
        if !candidate.windows_eligible {
            rejection_reasons.push(reason(
                VmSelectionReasonCode::WindowsUnsupported,
                format!("{} is not Windows eligible.", candidate.arm_sku_name),
            ));
        }
        if !candidate.cpu_architecture.eq_ignore_ascii_case("x64") {
            rejection_reasons.push(reason(
                VmSelectionReasonCode::ArchitectureUnsupported,
                format!(
                    "{} reports architecture {}.",
                    candidate.arm_sku_name, candidate.cpu_architecture
                ),
            ));
        }
        if !candidate.premium_io {
            rejection_reasons.push(reason(
                VmSelectionReasonCode::PremiumIoUnsupported,
                format!("{} does not support Premium I/O.", candidate.arm_sku_name),
            ));
        }
        if candidate.vcpus < request.minimum_vcpu {
            rejection_reasons.push(reason(
                VmSelectionReasonCode::InsufficientVcpu,
                format!(
                    "{} provides {} vCPU against {} required.",
                    candidate.arm_sku_name, candidate.vcpus, request.minimum_vcpu
                ),
            ));
        }
        if candidate.memory_gb.0 < request.minimum_memory_gb.0 {
            rejection_reasons.push(reason(
                VmSelectionReasonCode::InsufficientMemory,
                format!(
                    "{} provides {} GiB against {} GiB required.",
                    candidate.arm_sku_name, candidate.memory_gb, request.minimum_memory_gb
                ),
            ));
        }
        if request.requires_local_temp_disk {
            let local = candidate.local_temp_disk_gb.unwrap_or(DecimalValue::ZERO);
            if local.0 < request.minimum_local_temp_disk_gb.0 {
                rejection_reasons.push(reason(
                    VmSelectionReasonCode::InsufficientLocalTempDisk,
                    format!(
                        "{} provides {} GiB of local temporary storage against {} GiB required.",
                        candidate.arm_sku_name, local, request.minimum_local_temp_disk_gb
                    ),
                ));
            }
        }

        let data_disk_count = request
            .volumes
            .iter()
            .filter(|volume| volume.role == VmDiskRole::Data)
            .count();
        if data_disk_count > candidate.max_data_disk_count as usize {
            rejection_reasons.push(reason(
                VmSelectionReasonCode::DataDiskCountExceeded,
                format!(
                    "{} supports {} data disks against {} required.",
                    candidate.arm_sku_name, candidate.max_data_disk_count, data_disk_count
                ),
            ));
        }

        for volume in request.volumes {
            match select_disk(disk_catalog, request.azure_region, volume) {
                Some(disk) => disks.push(disk),
                None => rejection_reasons.push(reason(
                    VmSelectionReasonCode::NoEligibleDiskOffer,
                    format!(
                        "No managed disk offer in {} satisfies volume {} at {} GiB, {} IOPS, and {} MB/s.",
                        request.azure_region,
                        volume.label,
                        volume.capacity_gb,
                        volume.iops,
                        volume.throughput_mbps
                    ),
                )),
            }
        }

        if disks.len() == request.volumes.len() {
            let aggregate_iops: u64 = disks.iter().map(|disk| disk.provisioned_iops).sum();
            let aggregate_throughput: Decimal = disks
                .iter()
                .map(|disk| disk.provisioned_throughput_mbps.0)
                .sum();
            if aggregate_iops > candidate.uncached_disk_iops {
                rejection_reasons.push(reason(
                    VmSelectionReasonCode::AggregateDiskIopsExceeded,
                    format!(
                        "{} allows {} uncached disk IOPS against {} required.",
                        candidate.arm_sku_name, candidate.uncached_disk_iops, aggregate_iops
                    ),
                ));
            }
            if aggregate_throughput > Decimal::from(candidate.uncached_disk_throughput_mbps) {
                rejection_reasons.push(reason(
                    VmSelectionReasonCode::AggregateDiskThroughputExceeded,
                    format!(
                        "{} allows {} MB/s of uncached disk throughput against {} MB/s required.",
                        candidate.arm_sku_name,
                        candidate.uncached_disk_throughput_mbps,
                        aggregate_throughput
                    ),
                ));
            }
        }

        let hourly_rate = request.price_availability.and_then(|availability| {
            availability
                .vm_hourly_rates
                .get(&candidate.arm_sku_name.to_ascii_lowercase())
                .copied()
        });
        if request.price_availability.is_some() && hourly_rate.is_none() {
            rejection_reasons.push(reason(
                VmSelectionReasonCode::PriceUnavailable,
                format!(
                    "{} does not have a complete Windows PAYG rate in the coherent target snapshot.",
                    candidate.arm_sku_name
                ),
            ));
        }
        if let Some(availability) = request.price_availability {
            for disk in &disks {
                if !managed_disk_price_is_complete(availability, disk) {
                    rejection_reasons.push(reason(
                        VmSelectionReasonCode::PriceUnavailable,
                        format!(
                            "Managed disk {} for volume {} is missing a required coherent price dimension.",
                            disk.tier_key.as_deref().unwrap_or(&disk.offer_key),
                            disk.label
                        ),
                    ));
                }
            }
        }

        evaluations.push(VmCandidateEvaluation {
            arm_sku_name: candidate.arm_sku_name.clone(),
            vcpus: candidate.vcpus,
            memory_gb: candidate.memory_gb,
            eligible: rejection_reasons.is_empty(),
            rejection_reasons,
        });

        if evaluations
            .last()
            .is_some_and(|evaluation| evaluation.eligible)
        {
            eligible.push(EvaluatedCandidate {
                candidate,
                disks,
                hourly_rate,
            });
        }
    }

    evaluations.sort_by(|left, right| left.arm_sku_name.cmp(&right.arm_sku_name));

    let best = match request.requested_target_arm_sku {
        Some(requested) => eligible.into_iter().find(|evaluated| {
            evaluated
                .candidate
                .arm_sku_name
                .eq_ignore_ascii_case(requested)
        }),
        None => eligible.into_iter().min_by(|left, right| rank(left, right)),
    };
    let Some(best) = best else {
        let outcome_reasons = match request.requested_target_arm_sku {
            Some(requested) => vec![reason(
                VmSelectionReasonCode::TargetOverrideIneligible,
                format!(
                    "Requested target {requested} is absent or fails the reviewed region, lineage, lifecycle, compute, local-storage, or managed-disk requirements."
                ),
            )],
            None => vec![reason(
                VmSelectionReasonCode::LineageMismatch,
                format!(
                    "No current {requested_lineage:?} size in {} satisfies the vCPU, memory, disk, and aggregate limits.",
                    request.azure_region
                ),
            )],
        };
        return Ok(VmTargetSelection {
            mapping_status: MappingStatus::NoMapping,
            recommendation_status: VmRecommendationStatus::NoEligibleTarget,
            requested_lineage,
            selected: None,
            candidates: evaluations,
            outcome_reasons,
        });
    };

    let candidate = best.candidate;
    Ok(VmTargetSelection {
        mapping_status: MappingStatus::Mapped,
        recommendation_status: VmRecommendationStatus::Recommended,
        requested_lineage,
        selected: Some(SelectedVmTarget {
            arm_sku_name: candidate.arm_sku_name.clone(),
            display_family: candidate.display_family.clone(),
            lineage: candidate.lineage,
            generation: candidate.generation.clone(),
            generation_rank: candidate.generation_rank,
            lifecycle: candidate.lifecycle,
            azure_region: candidate.azure_region.clone(),
            vcpus: candidate.vcpus,
            memory_gb: candidate.memory_gb,
            max_data_disk_count: candidate.max_data_disk_count,
            uncached_disk_iops: candidate.uncached_disk_iops,
            uncached_disk_throughput_mbps: candidate.uncached_disk_throughput_mbps,
            local_temp_disk_gb: candidate.local_temp_disk_gb,
            disks: best.disks,
        }),
        candidates: evaluations,
        outcome_reasons: Vec::new(),
    })
}

fn validate_request(request: &VmTargetSelectionRequest<'_>) -> Result<(), VmTargetSelectionError> {
    if request.minimum_vcpu == 0 {
        return Err(VmTargetSelectionError::InvalidSourceVcpu);
    }
    if request.minimum_memory_gb.0 <= Decimal::ZERO {
        return Err(VmTargetSelectionError::InvalidSourceMemory);
    }
    if request.volumes.is_empty() {
        return Err(VmTargetSelectionError::NoVolumes);
    }
    if request
        .volumes
        .iter()
        .filter(|volume| volume.role == VmDiskRole::Os)
        .count()
        != 1
    {
        return Err(VmTargetSelectionError::OsVolumeCount);
    }
    Ok(())
}

/// Chooses the smallest capability-fit disk for one volume.
///
/// Preference order: smallest provisioned capacity, then an offer whose performance is provisioned
/// independently, then the offer key. Independent provisioning wins a capacity tie because it
/// preserves the source IOPS and throughput exactly instead of over-provisioning to a fixed tier.
fn select_disk(
    catalog: &ManagedDiskCatalog,
    azure_region: &str,
    volume: &VmVolumeRequirement,
) -> Option<SelectedManagedDisk> {
    let mut best: Option<SelectedManagedDisk> = None;

    for offer in &catalog.offers {
        if !offer
            .azure_regions
            .iter()
            .any(|region| region.eq_ignore_ascii_case(azure_region))
        {
            continue;
        }
        if !offer.allowed_roles.contains(&volume.role) {
            continue;
        }
        if volume.iops > offer.maximum_iops {
            continue;
        }
        if volume.throughput_mbps.0 > Decimal::from(offer.maximum_throughput_mbps) {
            continue;
        }

        let disk = if offer.performance_is_provisioned_independently {
            independent_disk(offer, volume)
        } else {
            tiered_disk(offer, volume)
        };

        let Some(disk) = disk else { continue };
        best = Some(match best {
            None => disk,
            Some(current) => {
                if prefer_disk(&disk, &current, catalog) {
                    disk
                } else {
                    current
                }
            }
        });
    }

    best
}

fn independent_disk(
    offer: &ManagedDiskOffer,
    volume: &VmVolumeRequirement,
) -> Option<SelectedManagedDisk> {
    let minimum = offer.minimum_capacity_gb.unwrap_or(DecimalValue::ZERO);
    let increment = offer
        .capacity_increment_gb
        .filter(|increment| increment.0 > Decimal::ZERO)?;

    let mut capacity = volume.capacity_gb.0.max(minimum.0);
    let remainder = capacity % increment.0;
    if remainder > Decimal::ZERO {
        capacity += increment.0 - remainder;
    }
    if capacity > offer.maximum_capacity_gb.0 {
        return None;
    }

    let included_iops = offer.included_iops.unwrap_or(0);
    let included_throughput = offer.included_throughput_mbps.unwrap_or(DecimalValue::ZERO);
    let provisioned_iops = volume.iops.max(included_iops);
    let provisioned_throughput = volume.throughput_mbps.0.max(included_throughput.0);

    Some(SelectedManagedDisk {
        volume_id: volume.volume_id,
        label: volume.label.clone(),
        role: volume.role,
        offer_key: offer.offer_key.clone(),
        display_name: offer.display_name.clone(),
        tier_key: None,
        capacity_gb: DecimalValue(capacity),
        provisioned_iops,
        provisioned_throughput_mbps: DecimalValue(provisioned_throughput),
        billed_additional_iops: provisioned_iops.saturating_sub(included_iops),
        billed_additional_throughput_mbps: DecimalValue(
            (provisioned_throughput - included_throughput.0).max(Decimal::ZERO),
        ),
    })
}

fn tiered_disk(
    offer: &ManagedDiskOffer,
    volume: &VmVolumeRequirement,
) -> Option<SelectedManagedDisk> {
    let tier = offer
        .tiers
        .iter()
        .filter(|tier| {
            tier.capacity_gb.0 >= volume.capacity_gb.0
                && tier.provisioned_iops >= volume.iops
                && tier.provisioned_throughput_mbps.0 >= volume.throughput_mbps.0
        })
        .min_by(|left, right| {
            left.capacity_gb
                .0
                .cmp(&right.capacity_gb.0)
                .then_with(|| left.tier_key.cmp(&right.tier_key))
        })?;

    Some(SelectedManagedDisk {
        volume_id: volume.volume_id,
        label: volume.label.clone(),
        role: volume.role,
        offer_key: offer.offer_key.clone(),
        display_name: offer.display_name.clone(),
        tier_key: Some(tier.tier_key.clone()),
        capacity_gb: tier.capacity_gb,
        provisioned_iops: tier.provisioned_iops,
        provisioned_throughput_mbps: tier.provisioned_throughput_mbps,
        billed_additional_iops: 0,
        billed_additional_throughput_mbps: DecimalValue::ZERO,
    })
}

fn prefer_disk(
    candidate: &SelectedManagedDisk,
    current: &SelectedManagedDisk,
    catalog: &ManagedDiskCatalog,
) -> bool {
    let independent = |disk: &SelectedManagedDisk| {
        catalog
            .offers
            .iter()
            .find(|offer| offer.offer_key == disk.offer_key)
            .is_some_and(|offer| offer.performance_is_provisioned_independently)
    };

    match candidate.capacity_gb.0.cmp(&current.capacity_gb.0) {
        Ordering::Less => true,
        Ordering::Greater => false,
        Ordering::Equal => match independent(candidate).cmp(&independent(current)) {
            Ordering::Greater => true,
            Ordering::Less => false,
            Ordering::Equal => candidate.offer_key < current.offer_key,
        },
    }
}

fn rank(left: &EvaluatedCandidate<'_>, right: &EvaluatedCandidate<'_>) -> Ordering {
    // Current lifecycle first, then the newest reviewed generation, then the smallest surplus.
    let lifecycle = |candidate: &VmSizeCandidate| match candidate.lifecycle {
        VmLifecycle::Current => 0_u8,
        VmLifecycle::Previous => 1,
    };

    lifecycle(left.candidate)
        .cmp(&lifecycle(right.candidate))
        .then_with(|| {
            right
                .candidate
                .generation_rank
                .cmp(&left.candidate.generation_rank)
        })
        .then_with(|| left.candidate.vcpus.cmp(&right.candidate.vcpus))
        .then_with(|| left.candidate.memory_gb.0.cmp(&right.candidate.memory_gb.0))
        .then_with(|| {
            disk_capacity(left)
                .cmp(&disk_capacity(right))
                .then_with(|| left.hourly_rate.cmp(&right.hourly_rate))
                .then_with(|| {
                    left.candidate
                        .arm_sku_name
                        .cmp(&right.candidate.arm_sku_name)
                })
        })
}

fn managed_disk_price_is_complete(
    availability: &VmPriceAvailability,
    disk: &SelectedManagedDisk,
) -> bool {
    let contains = |dimension| {
        availability
            .managed_disk_dimensions
            .contains(&VmDiskPriceKey {
                offer_key: disk.offer_key.clone(),
                tier_key: disk.tier_key.clone(),
                dimension,
            })
    };
    if disk.tier_key.is_some() {
        return contains(VmDiskPriceDimension::CapacityTier);
    }
    contains(VmDiskPriceDimension::CapacityGb)
        && (disk.billed_additional_iops == 0 || contains(VmDiskPriceDimension::AdditionalIops))
        && (disk.billed_additional_throughput_mbps.0 == Decimal::ZERO
            || contains(VmDiskPriceDimension::AdditionalThroughput))
}

fn disk_capacity(candidate: &EvaluatedCandidate<'_>) -> Decimal {
    candidate
        .disks
        .iter()
        .map(|disk| disk.capacity_gb.0)
        .sum::<Decimal>()
}

fn reason(code: VmSelectionReasonCode, detail: String) -> VmSelectionReason {
    VmSelectionReason { code, detail }
}

