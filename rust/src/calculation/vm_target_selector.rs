/// Semantic class of the source EC2 instance family. Derived from the reviewed policy below, not
/// from an ad hoc string test scattered through the calculation code.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum SourceClass {
    Burstable,
    GeneralPurpose,
    MemoryOptimized,
    HighFrequencyMemoryOptimized,
}

impl SourceClass {
    /// Preferred Azure lineage for this source class, per section 8.3.
    pub fn target_lineage(self) -> VmLineage {
        match self {
            Self::Burstable => VmLineage::Burstable,
            Self::GeneralPurpose => VmLineage::GeneralPurpose,
            Self::MemoryOptimized | Self::HighFrequencyMemoryOptimized => {
                VmLineage::MemoryOptimized
            }
        }
    }

    /// Caveat that must remain visible in the result whenever this class is mapped.
    pub fn required_caveat(self) -> Option<&'static str> {
        match self {
            Self::Burstable => Some(
                "The source is burstable and maps to the Azure burstable lineage. AWS and Azure CPU-credit models are not claimed to be identical.",
            ),
            Self::HighFrequencyMemoryOptimized => Some(
                "The source is a high-frequency instance. This target is a capacity fit on vCPU and memory only; per-core performance equivalence is not claimed and requires review outside this estimate.",
            ),
            Self::GeneralPurpose | Self::MemoryOptimized => None,
        }
    }
}

/// Reviewed AWS instance-family policy. An unlisted family has no recommended mapping rather than
/// a guessed one.
pub fn classify_source_instance(instance_type: &str) -> Option<SourceClass> {
    let family = instance_type
        .split('.')
        .next()?
        .trim()
        .to_ascii_lowercase()
        .chars()
        .take_while(|character| character.is_ascii_alphabetic())
        .collect::<String>();

    match family.as_str() {
        "t" => Some(SourceClass::Burstable),
        "m" => Some(SourceClass::GeneralPurpose),
        "r" => Some(SourceClass::MemoryOptimized),
        "z" => Some(SourceClass::HighFrequencyMemoryOptimized),
        _ => None,
    }
}

